def check_payment_gateway(order_id: str) -> str:
    """Retrieve payment transactions and item amount for an order ID."""
    record = MOCK_PAYMENT_DB.get(order_id)
    if not record:
        return json.dumps({"error": "Order ID not found in payment records."})
    return json.dumps(record)


def check_shipping_status(order_id: str) -> str:
    """Retrieve shipping status, delivery proof, and days since delivery."""
    record = MOCK_LOGISTICS_DB.get(order_id)
    if not record:
        return json.dumps({"error": "No shipping record found."})
    return json.dumps(record)


def get_customer_risk_profile(customer_id: str) -> str:
    """Retrieve customer account age and recent dispute frequency."""
    record = MOCK_CUSTOMER_HISTORY.get(customer_id)
    if not record:
        return json.dumps({"error": "Customer profile not found."})
    return json.dumps(record)


def execute_refund(order_id: str, amount: float, reason: str) -> str:
    """
    Gated refund tool.
    Hard-coded Python guardrail that the LLM cannot bypass.
    """
    # Hard guardrail: autonomous refund limit
    if amount > 50.00:
        return json.dumps({
            "status": "BLOCKED_BY_GUARDRAIL",
            "reason": (
                f"Refund amount (${amount:.2f}) exceeds the $50.00 autonomous limit. "
                "Must escalate to a Human Specialist."
            ),
        })

    if order_id not in MOCK_PAYMENT_DB:
        return json.dumps({"status": "FAILED", "reason": "Invalid Order ID."})

    return json.dumps({
        "status": "REFUND_EXECUTED",
        "order_id": order_id,
        "refunded_amount": amount,
        "reason": reason,
    })


def escalate_to_human_specialist(order_id: str, risk_level: str, evidence_summary: str) -> str:
    """Package evidence and route the case to a human specialist (HITL)."""
    return json.dumps({
        "status": "ESCALATED_TO_HUMAN",
        "ticket_id": f"ESC-{order_id}",
        "risk_level": risk_level,
        "evidence_brief": evidence_summary,
    })


