def get_llm() -> ChatOpenAI:
    """Create the LLM client using environment variables."""
    api_key = os.getenv("HKUST_OPENAI_API_KEY")
    base_url = os.getenv("HKUST_OPENAI_BASE_URL")

    if not api_key or not base_url:
        raise ValueError(
            "Missing HKUST_OPENAI_API_KEY or HKUST_OPENAI_BASE_URL environment variables."
        )

    return ChatOpenAI(
        base_url=base_url,
        api_key=api_key,
        model="gpt-4o-mini",
        temperature=0.3,
        default_headers={"api-key": api_key},
    )


