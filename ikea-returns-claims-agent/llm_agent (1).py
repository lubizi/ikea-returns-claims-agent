def run_llm_agent(customer_ticket: str, max_steps: int = 6) -> Dict[str, Any]:
    """
    Run the multi-step LLM agent.

    Returns a dictionary with:
    - final_message: the agent's reply to the customer
    - tool_trace: list of tools called and their results
    - status: COMPLETED or MAX_STEPS
    """
    llm = get_llm()
    llm_with_tools = llm.bind_tools(TOOLS)

    system_prompt = f"""You are an Autonomous Customer Dispute & Refund Resolution Agent for IKEA.
Follow this strict multi-step workflow:

1. INTAKE
   Identify the Order ID and the customer's claim type.
   If the Order ID or claim reason is missing, politely ask for it before calling any tools.

2. DATA GATHERING
   Once you have the Order ID, always call:
   - check_payment_gateway
   - check_shipping_status
   - get_customer_risk_profile
   before making a final decision.

3. POLICY EVALUATION
   Evaluate the findings against this policy:
{IKEA_POLICY}

4. ACTION
   - Clear duplicate charge or low-risk valid claim ≤ $50 → call execute_refund.
   - Clear policy violation (e.g., transit damage reported > 30 days after delivery) → politely reject with evidence.
   - Claim > $50, delivery conflict (DELIVERED with proof but customer claims missing/stolen),
     or high dispute history (≥ 3 in 90 days) → call escalate_to_human_specialist
     with a concise evidence brief.

5. RESPONSE
   Write a clear, polite final message to the customer explaining the outcome.
"""

    messages = [
        SystemMessage(content=system_prompt),
        HumanMessage(content=customer_ticket),
    ]

    tool_trace: List[Dict[str, Any]] = []

    for _ in range(max_steps):
        ai_msg = llm_with_tools.invoke(messages)
        messages.append(ai_msg)

        if ai_msg.tool_calls:
            for tool_call in ai_msg.tool_calls:
                fn_name = tool_call["name"]
                fn_args = tool_call["args"]
                tool_result = TOOL_MAP[fn_name](**fn_args)

                tool_trace.append({
                    "tool": fn_name,
                    "args": fn_args,
                    "result": tool_result,
                })

                messages.append(
                    ToolMessage(content=tool_result, tool_call_id=tool_call["id"])
                )
        else:
            return {
                "final_message": ai_msg.content or "",
                "tool_trace": tool_trace,
                "status": "COMPLETED",
            }

    return {
        "final_message": "The agent reached the maximum number of steps. Please review this case manually.",
        "tool_trace": tool_trace,
        "status": "MAX_STEPS",
    }


